# PATH: app/graph/state.py

"""
ساختار state برای معماری Agent + Tools.

conversation_context عمداً جدا از messages نگه داشته می‌شود.
messages برای تاریخچه‌ی مکالمه و نتایج ابزارهاست؛
conversation_context برای context فعال همین مکالمه است.

این جداسازی باعث می‌شود Follow-upهایی مثل:
    «چرا؟»
    «دلیلش؟»
    «همون محصول؟»
بدون اتکا به حدس LLM به context قبلی متصل شوند.
"""

from __future__ import annotations

from typing import Annotated, Any, TypedDict
from operator import add


class GraphState(TypedDict, total=False):

    # ============================================================
    # تاریخچه‌ی مکالمه
    # ============================================================

    messages: Annotated[list[dict[str, Any]], add]

    # ============================================================
    # Context فعال مکالمه
    #
    # این فیلد توسط main.py به‌صورت deterministic ساخته می‌شود.
    #
    # نمونه:
    # {
    #     "is_follow_up": True,
    #     "product_id": 158423,
    #     "product_title": "...",
    #     "metric": "units_sold",
    #     "metric_label": "تعداد خرید",
    #     "period_start": "2022-09-01",
    #     "period_end": "2023-03-01",
    #     "period_label": "شش ماه اخیر",
    #     "previous_result": {...}
    # }
    #
    # این context نباید توسط LLM حدس زده شود.
    # ============================================================

    conversation_context: dict[str, Any]

    # ============================================================
    # شمارنده‌ی دور Agent <-> Tools
    # ============================================================

    iterations: int

    # ============================================================
    # شمارنده‌ی خطاهای متوالی ابزارها
    # ============================================================

    consecutive_tool_errors: int

    # ============================================================
    # رد ابزارها برای validation / audit
    # ============================================================

    tool_trace: Annotated[list[dict[str, Any]], add]

    # ============================================================
    # پاسخ نهایی
    # ============================================================

    final_answer: str

    # ============================================================
    # نتیجه‌ی validation
    # ============================================================

    validation: dict[str, Any]

    # ============================================================
    # خطاها
    # ============================================================

    errors: Annotated[list[str], add]